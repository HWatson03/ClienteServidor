CREATE TABLE tareas_copia (
    id_tarea_copia BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL REFERENCES usuarios(id_usuario),
    id_archivo_origen BIGINT REFERENCES archivos(id_archivo),
    id_carpeta_origen BIGINT REFERENCES carpetas(id_carpeta),
    id_carpeta_destino BIGINT NOT NULL REFERENCES carpetas(id_carpeta),
    total_bytes BIGINT NOT NULL DEFAULT 0,
    bytes_copiados BIGINT NOT NULL DEFAULT 0,
    estado_tarea VARCHAR(20) NOT NULL DEFAULT 'EN_PROCESO',
    error VARCHAR(500),
    fecha_creacion TIMESTAMP NOT NULL,
    creado_por VARCHAR(100) NOT NULL,
    fecha_ultima_modificacion TIMESTAMP NOT NULL,
    modificado_por VARCHAR(100) NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'ACTIVO'
);
CREATE INDEX idx_tarea_copia_propietario ON tareas_copia (id_usuario);
