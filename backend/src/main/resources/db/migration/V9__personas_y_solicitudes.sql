CREATE TABLE personas (
    id_persona BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombres VARCHAR(100) NOT NULL,
    apellido_paterno VARCHAR(100) NOT NULL,
    apellido_materno VARCHAR(100) NOT NULL,
    ci VARCHAR(30) NOT NULL,
    correo VARCHAR(180) NOT NULL,
    telefono VARCHAR(40) NOT NULL,
    fecha_creacion TIMESTAMP NOT NULL,
    creado_por VARCHAR(100) NOT NULL,
    fecha_ultima_modificacion TIMESTAMP NOT NULL,
    modificado_por VARCHAR(100) NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'ACTIVO'
);
CREATE UNIQUE INDEX uk_persona_ci ON personas (LOWER(ci));
CREATE UNIQUE INDEX uk_persona_correo ON personas (LOWER(correo));

ALTER TABLE usuarios ADD COLUMN id_persona BIGINT UNIQUE REFERENCES personas(id_persona);

CREATE TABLE solicitudes_usuario (
    id_solicitud BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombres VARCHAR(100) NOT NULL,
    apellido_paterno VARCHAR(100) NOT NULL,
    apellido_materno VARCHAR(100) NOT NULL,
    ci VARCHAR(30) NOT NULL,
    correo VARCHAR(180) NOT NULL,
    telefono VARCHAR(40) NOT NULL,
    nombre_usuario VARCHAR(50) NOT NULL,
    contrasena_hash VARCHAR(255) NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
    fecha_solicitud TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    revisada_en TIMESTAMP,
    revisada_por VARCHAR(100)
);
CREATE UNIQUE INDEX uk_solicitud_usuario_pendiente ON solicitudes_usuario (LOWER(nombre_usuario)) WHERE estado = 'PENDIENTE';
CREATE INDEX idx_solicitud_estado_fecha ON solicitudes_usuario (estado, fecha_solicitud DESC);
