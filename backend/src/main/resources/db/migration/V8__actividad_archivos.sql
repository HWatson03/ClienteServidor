CREATE TABLE IF NOT EXISTS actividad_archivos (
    id_actividad BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL REFERENCES usuarios(id_usuario),
    accion VARCHAR(30) NOT NULL,
    nombre_recurso VARCHAR(255) NOT NULL,
    bytes BIGINT NOT NULL DEFAULT 0,
    ocurrida_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_actividad_archivos_fecha
    ON actividad_archivos (ocurrida_en DESC);
