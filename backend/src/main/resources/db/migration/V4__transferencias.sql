CREATE TABLE cargas (
    id_carga BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL REFERENCES usuarios(id_usuario),
    id_carpeta_destino BIGINT NOT NULL REFERENCES carpetas(id_carpeta),
    nombre_archivo VARCHAR(255) NOT NULL,
    tamano_esperado BIGINT NOT NULL,
    offset_confirmado BIGINT NOT NULL DEFAULT 0,
    clave_temporal VARCHAR(255) NOT NULL,
    estado_carga VARCHAR(20) NOT NULL DEFAULT 'INICIADA',
    expira_en TIMESTAMP NOT NULL,
    fecha_creacion TIMESTAMP NOT NULL,
    creado_por VARCHAR(100) NOT NULL,
    fecha_ultima_modificacion TIMESTAMP NOT NULL,
    modificado_por VARCHAR(100) NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'ACTIVO'
);
CREATE INDEX idx_carga_usuario ON cargas (id_usuario);
CREATE INDEX idx_carga_expiracion ON cargas (expira_en);
