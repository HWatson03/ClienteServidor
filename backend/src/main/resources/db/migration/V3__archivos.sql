CREATE TABLE carpetas (
    id_carpeta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL REFERENCES usuarios(id_usuario),
    id_carpeta_padre BIGINT REFERENCES carpetas(id_carpeta),
    nombre VARCHAR(255) NOT NULL,
    es_raiz BOOLEAN NOT NULL DEFAULT FALSE,
    en_papelera BOOLEAN NOT NULL DEFAULT FALSE,
    grupo_eliminacion VARCHAR(64),
    eliminado_en TIMESTAMP,
    fecha_creacion TIMESTAMP NOT NULL,
    creado_por VARCHAR(100) NOT NULL,
    fecha_ultima_modificacion TIMESTAMP NOT NULL,
    modificado_por VARCHAR(100) NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'ACTIVO'
);
CREATE INDEX idx_carpeta_propietario ON carpetas (id_usuario);
CREATE INDEX idx_carpeta_padre ON carpetas (id_carpeta_padre);

CREATE TABLE archivos (
    id_archivo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL REFERENCES usuarios(id_usuario),
    id_carpeta BIGINT NOT NULL REFERENCES carpetas(id_carpeta),
    nombre_visible VARCHAR(255) NOT NULL,
    clave_disco VARCHAR(255) NOT NULL UNIQUE,
    tamano BIGINT NOT NULL,
    tipo_mime VARCHAR(128),
    en_papelera BOOLEAN NOT NULL DEFAULT FALSE,
    grupo_eliminacion VARCHAR(64),
    eliminado_en TIMESTAMP,
    fecha_creacion TIMESTAMP NOT NULL,
    creado_por VARCHAR(100) NOT NULL,
    fecha_ultima_modificacion TIMESTAMP NOT NULL,
    modificado_por VARCHAR(100) NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'ACTIVO'
);
CREATE INDEX idx_archivo_propietario ON archivos (id_usuario);
CREATE INDEX idx_archivo_carpeta ON archivos (id_carpeta);

CREATE TABLE cuota_usuario (
    id_cuota_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL UNIQUE REFERENCES usuarios(id_usuario),
    bytes_ocupados BIGINT NOT NULL DEFAULT 0,
    bytes_reservados BIGINT NOT NULL DEFAULT 0,
    fecha_creacion TIMESTAMP NOT NULL,
    creado_por VARCHAR(100) NOT NULL,
    fecha_ultima_modificacion TIMESTAMP NOT NULL,
    modificado_por VARCHAR(100) NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'ACTIVO'
);
