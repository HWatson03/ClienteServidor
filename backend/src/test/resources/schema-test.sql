CREATE TABLE IF NOT EXISTS historial_almacenamiento (
    id_historial BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    capturado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    bytes_total_servidor BIGINT NOT NULL,
    bytes_disponibles_servidor BIGINT NOT NULL,
    bytes_ocupados_clientes BIGINT NOT NULL,
    cantidad_clientes BIGINT NOT NULL
);
